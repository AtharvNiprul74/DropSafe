def validate_dataset(
    df,
    academic_periods,
):
    """
    Validate the generated learning_components dataset.
    """

    required_columns = [
        "id",
        "organization_id",
        "academic_period_id",
        "component_code",
        "name",
        "description",
        "component_type",
        "maximum_marks",
        "passing_marks",
        "status",
        "created_at",
        "updated_at",
        "created_by",
        "updated_by",
    ]

    results = {}

    missing_columns = [
        column
        for column in required_columns
        if column not in df.columns
    ]

    results["missing_columns"] = missing_columns

    results["rows"] = len(df)
    results["columns"] = len(df.columns)

    results["missing_values"] = int(
        df.isnull().sum().sum()
    )

    results["duplicate_rows"] = int(
        df.duplicated().sum()
    )

    results["duplicate_ids"] = int(
        df["id"].duplicated().sum()
    )

    results["duplicate_component_codes"] = int(
        df.duplicated(
            subset=[
                "organization_id",
                "academic_period_id",
                "component_code",
            ]
        ).sum()
    )

    results["duplicate_names"] = int(
        df.duplicated(
            subset=[
                "organization_id",
                "academic_period_id",
                "name",
            ]
        ).sum()
    )

    results["empty_component_codes"] = int(
        df["component_code"]
        .astype(str)
        .str.strip()
        .eq("")
        .sum()
    )

    results["empty_names"] = int(
        df["name"]
        .astype(str)
        .str.strip()
        .eq("")
        .sum()
    )

    results["invalid_component_types"] = int(
        (
            ~df["component_type"].isin(
                COMPONENT_TYPES
            )
        ).sum()
    )

    results["invalid_status"] = int(
        (
            ~df["status"].isin(
                STATUSES
            )
        ).sum()
    )

    results["invalid_maximum_marks"] = int(
        (
            pd.to_numeric(
                df["maximum_marks"],
                errors="coerce",
            ).isna()
            |
            (
                pd.to_numeric(
                    df["maximum_marks"],
                    errors="coerce",
                )
                <= 0
            )
        ).sum()
    )

    results["invalid_passing_marks"] = int(
        (
            pd.to_numeric(
                df["passing_marks"],
                errors="coerce",
            ).isna()
            |
            (
                pd.to_numeric(
                    df["passing_marks"],
                    errors="coerce",
                )
                < 0
            )
        ).sum()
    )

    results["passing_marks_exceed_maximum"] = int(
        (
            pd.to_numeric(
                df["passing_marks"],
                errors="coerce",
            )
            >
            pd.to_numeric(
                df["maximum_marks"],
                errors="coerce",
            )
        ).sum()
    )

    valid_period_ids = set(
        academic_periods["id"].astype(str)
    )

    invalid_reference_mask = (
        ~df["academic_period_id"]
        .astype(str)
        .isin(valid_period_ids)
    )

    results["invalid_period_references"] = int(
        invalid_reference_mask.sum()
    )

    # --------------------------------------------------------
    # Period coverage validation
    # --------------------------------------------------------

    covered_period_ids = set(
        df["academic_period_id"]
        .astype(str)
    )

    results["periods_without_components"] = int(
        len(
            valid_period_ids - covered_period_ids
        )
    )

    period_org_map = dict(
        zip(
            academic_periods["id"].astype(str),
            academic_periods[
                "organization_id"
            ].astype(str),
        )
    )

    expected_organizations = (
        df["academic_period_id"]
        .astype(str)
        .map(period_org_map)
    )

    results["organization_mismatches"] = int(
        (
            expected_organizations
            != df["organization_id"].astype(str)
        ).sum()
    )

    results["validation_passed"] = (
        len(missing_columns) == 0
        and results["duplicate_rows"] == 0
        and results["duplicate_ids"] == 0
        and results["duplicate_component_codes"] == 0
        and results["duplicate_names"] == 0
        and results["empty_component_codes"] == 0
        and results["empty_names"] == 0
        and results["invalid_component_types"] == 0
        and results["invalid_status"] == 0
        and results["invalid_maximum_marks"] == 0
        and results["invalid_passing_marks"] == 0
        and results["passing_marks_exceed_maximum"] == 0
        and results["invalid_period_references"] == 0
        and results["periods_without_components"] == 0
        and results["organization_mismatches"] == 0
    )

    return results


