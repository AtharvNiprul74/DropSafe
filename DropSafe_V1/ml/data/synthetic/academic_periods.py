from pathlib import Path
from datetime import date, datetime, timezone
import uuid
import pandas as pd

BASE_DIR = Path(__file__).resolve().parents[2]
RAW_DIR = BASE_DIR / "data" / "raw"
REPORT_DIR = BASE_DIR / "data" / "synthetic"
LEVELS_FILE = RAW_DIR / "learning_levels.csv"
OUTPUT_FILE = RAW_DIR / "academic_periods.csv"
REPORT_FILE = REPORT_DIR / "academic_periods.md"

FIRST_START_YEAR = 2022
STATUSES = ["PLANNED", "ACTIVE", "COMPLETED", "ARCHIVED"]


def generate_uuid():
    timestamp_ms = int(datetime.now(timezone.utc).timestamp() * 1000)
    random_bits = uuid.uuid4().int
    value = (
        ((timestamp_ms & ((1 << 48) - 1)) << 80)
        | (0x7 << 76)
        | (((random_bits >> 64) & 0xFFF) << 64)
        | (0b10 << 62)
        | (random_bits & ((1 << 62) - 1))
    )
    return str(uuid.UUID(int=value))


def utc_now():
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def load_levels():
    if not LEVELS_FILE.exists():
        raise FileNotFoundError(
            f"Missing {LEVELS_FILE}. Generate learning_levels.csv first."
        )
    df = pd.read_csv(
        LEVELS_FILE,
        dtype={"id": str, "organization_id": str, "learning_program_id": str},
    )
    required = ["id", "organization_id", "learning_program_id", "level_number"]
    missing = [column for column in required if column not in df.columns]
    if missing:
        raise ValueError(f"learning_levels.csv is missing columns: {missing}")
    if df.empty:
        raise ValueError("learning_levels.csv is empty.")
    if df["id"].duplicated().any():
        raise ValueError("learning_levels.csv contains duplicate IDs.")
    if df.duplicated(
        ["organization_id", "learning_program_id", "level_number"]
    ).any():
        raise ValueError("Each program must have only one record per level number.")
    return df


def generate_periods(levels):
    rows = []
    for level in levels.sort_values(
        ["learning_program_id", "level_number"]
    ).to_dict("records"):
        level_number = int(level["level_number"])
        start_year = FIRST_START_YEAR + level_number - 1
        start = date(start_year, 7, 1)
        end = date(start_year + 1, 5, 31)

        if end < date.today():
            status = "COMPLETED"
        elif start <= date.today() <= end:
            status = "ACTIVE"
        else:
            status = "PLANNED"

        now = utc_now()
        # Full program UUID avoids collisions caused by using only its first 8 chars.
        program_id = str(level["learning_program_id"])
        period_code = f"{program_id}-L{level_number}-{start_year}"

        rows.append({
            "id": generate_uuid(),
            "organization_id": level["organization_id"],
            "learning_level_id": level["id"],
            "period_code": period_code,
            "name": f"Academic Period {start_year}-{start_year + 1} - Level {level_number}",
            "start_date": start.isoformat(),
            "end_date": end.isoformat(),
            "status": status,
            "created_at": now,
            "updated_at": now,
            "created_by": None,
            "updated_by": None,
        })
    return pd.DataFrame(rows)


def validate(df, levels):
    required_columns = [
        "id", "organization_id", "learning_level_id", "period_code", "name",
        "start_date", "end_date", "status", "created_at", "updated_at",
        "created_by", "updated_by",
    ]
    missing_columns = [column for column in required_columns if column not in df.columns]
    level_ids = set(levels["id"].astype(str))
    level_org = dict(zip(levels["id"].astype(str), levels["organization_id"].astype(str)))
    mapped_org = df["learning_level_id"].astype(str).map(level_org)
    starts = pd.to_datetime(df["start_date"], errors="coerce")
    ends = pd.to_datetime(df["end_date"], errors="coerce")

    results = {
        "rows": len(df),
        "missing_columns": missing_columns,
        "duplicate_ids": int(df["id"].duplicated().sum()),
        "duplicate_period_codes": int(df["period_code"].duplicated().sum()),
        "invalid_level_refs": int((~df["learning_level_id"].astype(str).isin(level_ids)).sum()),
        "organization_mismatches": int((mapped_org != df["organization_id"].astype(str)).sum()),
        "invalid_dates": int((starts.isna() | ends.isna()).sum()),
        "invalid_date_ranges": int((starts >= ends).sum()),
        "invalid_statuses": int((~df["status"].isin(STATUSES)).sum()),
    }
    results["validation_passed"] = (
        not results["missing_columns"]
        and results["duplicate_ids"] == 0
        and results["duplicate_period_codes"] == 0
        and results["invalid_level_refs"] == 0
        and results["organization_mismatches"] == 0
        and results["invalid_dates"] == 0
        and results["invalid_date_ranges"] == 0
        and results["invalid_statuses"] == 0
    )
    return results


def main():
    levels = load_levels()
    df = generate_periods(levels)
    RAW_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    df.to_csv(OUTPUT_FILE, index=False)
    result = validate(df, levels)

    REPORT_FILE.write_text(
        "# Academic Periods Synthetic Dataset\n\n"
        f"- Learning levels: {len(levels)}\n"
        f"- Academic periods generated: {len(df)}\n"
        "- Rule: one period per learning level; levels 1-4 map to consecutive academic years.\n"
        "- Period codes include the full program UUID to avoid short-prefix collisions.\n"
        "- Target/dropout labels: not generated.\n\n"
        f"## Validation\n\n```text\n{result}\n```\n",
        encoding="utf-8",
    )

    print(f"Learning levels: {len(levels)}")
    print(f"Academic periods: {len(df)}")
    print(f"CSV: {OUTPUT_FILE}")
    print(f"Report: {REPORT_FILE}")
    print(f"Validation: {'PASS' if result['validation_passed'] else 'FAIL'}")
    print(f"Duplicate period codes: {result['duplicate_period_codes']}")
    print(f"Duplicate IDs: {result['duplicate_ids']}")
    print(f"Invalid level references: {result['invalid_level_refs']}")
    print(f"Organization mismatches: {result['organization_mismatches']}")
    print(f"Invalid dates: {result['invalid_dates']}")
    print(f"Invalid date ranges: {result['invalid_date_ranges']}")
    print(f"Invalid statuses: {result['invalid_statuses']}")

    if not result["validation_passed"]:
        raise SystemExit("Academic-period validation failed.")


if __name__ == "__main__":
    main()
