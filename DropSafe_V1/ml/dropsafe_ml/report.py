def _load_requests(path: Path):
    from dropsafe_ml.schemas import PredictionRequest
    text = Path(path).read_text().strip()
    if path.suffix == ".jsonl":
        items = [json.loads(line) for line in text.splitlines() if line.strip()]
    else:
        obj = json.loads(text)
        items = obj.get("requests", [obj]) if isinstance(obj, dict) else obj
    return [PredictionRequest.model_validate(i) for i in items]  # extra keys (labels) ignored


def risk_report(input_path: Path | str, registry: ModelRegistry | None = None,
                out_dir: Path | None = None, title: str | None = None) -> dict[str, Path]:
    from dropsafe_ml.predictor import RiskPredictor

    input_path = Path(input_path)
    predictor = RiskPredictor.from_registry(registry or ModelRegistry())
    reqs = _load_requests(input_path)
    res = predictor.predict_batch(reqs)
    meta = predictor.metadata

    predicted = [r for r in res if r.status == "PREDICTED"]
    insufficient = [r for r in res if r.status == "INSUFFICIENT_EVIDENCE"]
    counts = Counter(r.prediction.risk_label.value for r in predicted)
    orgs = sorted({r.organization_id for r in res})

    # drivers among HIGH/MEDIUM
    drivers = Counter()
    for r in predicted:
        if r.prediction.risk_label.value in ("HIGH", "MEDIUM"):
            for f in r.prediction.top_factors:
                if f.direction == "RAISES_RISK":
                    drivers[f.label] += 1

    # charts
    fig, ax = plt.subplots(figsize=(5, 3.2))
    labels = ["HIGH", "MEDIUM", "LOW"]
    vals = [counts.get(b, 0) for b in labels]
    bars = ax.bar(labels, vals, color=[BAND_COLORS[b] for b in labels])
    ax.bar_label(bars)
    ax.set_title("Students by risk band")
    ax.set_ylabel("Students")
    ax.spines[["top", "right"]].set_visible(False)
    chart_bands = _fig_b64(fig)

    chart_drivers = ""
    if drivers:
        fig, ax = plt.subplots(figsize=(5, 3.2))
        items = drivers.most_common()[::-1]
        ax.barh([k for k, _ in items], [v for _, v in items], color="#3b6fd8")
        ax.set_title("Top risk drivers (HIGH + MEDIUM students)")
        ax.set_xlabel("Students where factor is a top driver")
        ax.spines[["top", "right"]].set_visible(False)
        chart_drivers = _fig_b64(fig)

    def rows_for(band: str) -> str:
        sel = sorted((r for r in predicted if r.prediction.risk_label.value == band),
                     key=lambda r: -r.prediction.risk_probability)
        if not sel:
            return "<tr><td colspan='9'>None</td></tr>"
        out = []
        for r in sel:
            s, p = r.snapshot, r.prediction
            reasons = "<br>".join(_e(f.description) for f in p.top_factors if f.direction == "RAISES_RISK") or "—"
            out.append(
                f"<tr><td>{_e(r.student_id)}</td><td>{_e(r.enrollment_id)}</td>"
                f"<td><b>{p.risk_probability:.1f}%</b></td><td>{p.prediction_confidence:.0f}</td>"
                f"<td>{'' if s.attendance_percentage is None else f'{s.attendance_percentage:.1f}%'}</td>"
                f"<td>{'' if s.overall_marks_percentage is None else f'{s.overall_marks_percentage:.1f}%'}</td>"
                f"<td>{s.failed_learning_components}</td><td>{s.backlog_count}</td><td>{reasons}</td></tr>")
        return "".join(out)

    head = ("<tr><th>Student</th><th>Enrollment</th><th>Risk prob.</th><th>Confidence</th>"
            "<th>Attendance</th><th>Marks</th><th>Failed</th><th>Backlogs</th><th>Why (top factors)</th></tr>")
    insuff_rows = "".join(
        f"<tr><td>{_e(r.student_id)}</td><td>{_e(r.enrollment_id)}</td><td>{'<br>'.join(_e(x) for x in r.missing_evidence)}</td></tr>"
        for r in insufficient) or "<tr><td colspan='3'>None</td></tr>"

    title = title or f"Student Risk Report — {input_path.stem}"
    n = len(res)
    body = f"""
<h1>{_e(title)}</h1>
<div class="sub">Organization(s): {_e(', '.join(orgs))} · Model <b>{_e(meta['model_version'])}</b> · features {_e(meta['feature_version'])} · source file {_e(input_path.name)}</div>
<div class="banner conf"><b>CONFIDENTIAL. Contains HIGH-sensitivity student data.</b> Visible only to the Organization Admin and the assigned Mentor (PRD §17). Do not share these results with students or through the chatbot.</div>
{"<div class='banner warn'><b>⚠ Model trained on SIMULATED data.</b> These results are for demonstration only.</div>" if meta.get('training_dataset_synthetic') else ""}
<div class="banner info">Decision support only. Every student listed needs <b>human review</b>. This report does not create interventions or counseling sessions.</div>

<div class="cards">
 <div class="card"><div class="k">Students</div><div class="v">{n}</div></div>
 <div class="card"><div class="k">High risk</div><div class="v" style="color:{BAND_COLORS['HIGH']}">{counts.get('HIGH', 0)}</div></div>
 <div class="card"><div class="k">Medium risk</div><div class="v" style="color:{BAND_COLORS['MEDIUM']}">{counts.get('MEDIUM', 0)}</div></div>
 <div class="card"><div class="k">Low risk</div><div class="v" style="color:{BAND_COLORS['LOW']}">{counts.get('LOW', 0)}</div></div>
 <div class="card"><div class="k">Insufficient evidence</div><div class="v">{len(insufficient)}</div></div>
</div>

<h2>Overview</h2>
<div class="imgs"><img src="{chart_bands}" alt="Bands">{f'<img src="{chart_drivers}" alt="Drivers">' if chart_drivers else ''}</div>

<h2>{_pill('HIGH')} High-risk students: review first ({counts.get('HIGH', 0)})</h2>
<table>{head}{rows_for('HIGH')}</table>

<h2>{_pill('MEDIUM')} Medium-risk students: monitor ({counts.get('MEDIUM', 0)})</h2>
<table>{head}{rows_for('MEDIUM')}</table>

<h2>No prediction: insufficient evidence ({len(insufficient)})</h2>
<p class="sub">The model does not guess. Collect the missing evidence, then re-run.</p>
<table><tr><th>Student</th><th>Enrollment</th><th>Missing evidence</th></tr>{insuff_rows}</table>

<p class="sub" style="margin-top:20px">{counts.get('LOW', 0)} LOW-risk students are listed in the CSV export only.</p>
"""
    out_dir = Path(out_dir or REPORTS_DIR)
    out_dir.mkdir(parents=True, exist_ok=True)
    name = input_path.parent.name if input_path.stem in ("students", "requests") else input_path.stem
    stem = f"risk_report_{name}"
    html_path = out_dir / f"{stem}.html"
    html_path.write_text(_page(title, body))

    csv_path = out_dir / f"{stem}.csv"
    with csv_path.open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["organization_id", "student_id", "enrollment_id", "status", "risk_label",
                    "risk_probability", "prediction_confidence", *config.FEATURE_COLUMNS,
                    "top_factors", "missing_evidence", "ai_model_version", "feature_version", "generated_at"])
        for r in res:
            p, s = r.prediction, r.snapshot
            w.writerow([
                r.organization_id, r.student_id, r.enrollment_id, r.status.value,
                p.risk_label.value if p else "", p.risk_probability if p else "",
                p.prediction_confidence if p else "",
                *[(getattr(s, c) if s and getattr(s, c) is not None else "") for c in config.FEATURE_COLUMNS],
                " | ".join(f.description for f in p.top_factors) if p else "",
                " | ".join(r.missing_evidence), meta["model_version"], meta["feature_version"],
                p.generated_at.isoformat() if p else "",
            ])
    return {"html": html_path, "csv": csv_path}
