def model_report(model_version: str | None = None, registry: ModelRegistry | None = None,
                 out_dir: Path | None = None) -> dict[str, Path]:
    registry = registry or ModelRegistry()
    if model_version is None:
        active = registry.get_active()
        if not active:
            raise SystemExit("No ACTIVE model. Train/deploy first or pass --version.")
        model_version = active["model_version"]
    mdir = registry.model_dir(model_version)
    meta = json.loads((mdir / "metadata.json").read_text())
    m = json.loads((mdir / "metrics.json").read_text())
    reg_entry = next((r for r in registry.list() if r["model_version"] == model_version), None)
    status = reg_entry["status"] if reg_entry else "NOT DEPLOYED"

    gbm, base = m["lightgbm_calibrated"], m["baseline_logistic_regression"]
    bands = m["risk_bands_test"]
    high, med = bands["HIGH"], bands["MEDIUM"]
    recall_hm = high["share_of_all_disengaged_captured"] + med["share_of_all_disengaged_captured"]

    def cmp(metric: str, higher_better: bool) -> str:
        a, b = gbm[metric], base[metric]
        better = (a > b) if higher_better else (a < b)
        cls = "good" if better else ("bad" if abs(a - b) > 0.005 else "")
        return f"<span class='{cls}'>{a:.4f}</span>"

    # Findings (computed, not hard-coded)
    findings = []
    findings.append(
        f"The model ranks students well on held-out data (ROC-AUC {gbm['roc_auc']:.3f}; "
        f"0.5 = random, 1.0 = perfect).")
    findings.append(
        f"HIGH band: {_pct(high['share_of_students'])} of students, of whom "
        f"{_pct(high['observed_disengagement_rate'])} actually disengaged; it captures "
        f"{_pct(high['share_of_all_disengaged_captured'])} of all disengaged students.")
    findings.append(
        f"HIGH + MEDIUM together capture {_pct(recall_hm)} of disengaged students; "
        f"{_pct(bands['LOW']['share_of_all_disengaged_captured'])} are missed in LOW "
        f"(LOW-band disengagement rate {_pct(bands['LOW']['observed_disengagement_rate'])}).")
    diff = gbm["roc_auc"] - base["roc_auc"]
    if abs(diff) < 0.01:
        findings.append(
            "LightGBM and the logistic-regression baseline perform about the same. On synthetic data "
            "this is expected (the outcome was simulated with a mostly linear formula). Re-check on real data.")
    elif diff > 0:
        findings.append(f"LightGBM beats the baseline by {diff:.3f} ROC-AUC.")
    else:
        findings.append(f"The baseline beats LightGBM by {-diff:.3f} ROC-AUC. Consider the simpler model.")
    imp = m["global_feature_importance_mean_abs_shap"]
    top3 = [config.FEATURE_LABELS[k] for k in list(imp)[:3]]
    findings.append(f"Strongest risk drivers: {', '.join(top3)}.")
    findings.append(f"{meta['dataset_rows_excluded_insufficient_evidence']} records were excluded from "
                    f"training because they failed the evidence-sufficiency gate.")

    synthetic = meta.get("training_dataset_synthetic", False)
    body = f"""
<h1>Model Evaluation Report</h1>
<div class="sub">{_e(meta['model_name'])} · <b>{_e(model_version)}</b> · status <b>{_e(status)}</b></div>
{"<div class='banner warn'><b>⚠ Trained on SIMULATED data.</b> These metrics only show that the pipeline works. They say nothing about real-world accuracy. Do not use this model for decisions about real students.</div>" if synthetic else ""}
<div class="banner info">Decision support only. Humans decide interventions; a HIGH prediction never automatically creates an intervention or counseling session.</div>

<div class="cards">
 <div class="card"><div class="k">ROC-AUC</div><div class="v">{gbm['roc_auc']:.3f}</div></div>
 <div class="card"><div class="k">PR-AUC</div><div class="v">{gbm['pr_auc']:.3f}</div></div>
 <div class="card"><div class="k">Brier score</div><div class="v">{gbm['brier']:.3f}</div></div>
 <div class="card"><div class="k">HIGH precision</div><div class="v">{_pct(high['observed_disengagement_rate'])}</div></div>
 <div class="card"><div class="k">HIGH+MED recall</div><div class="v">{_pct(recall_hm)}</div></div>
 <div class="card"><div class="k">Test positive rate</div><div class="v">{_pct(m['test_positive_rate'])}</div></div>
</div>

<h2>Key findings</h2><ul>{''.join(f'<li>{_e(f)}</li>' for f in findings)}</ul>

<h2>Model identity &amp; traceability (ai_model_metadata)</h2>
<table>
<tr><th>Model name</th><td>{_e(meta['model_name'])}</td><th>Model version</th><td>{_e(model_version)}</td></tr>
<tr><th>Algorithm</th><td colspan="3">{_e(meta['algorithm'])}</td></tr>
<tr><th>Feature version</th><td>{_e(meta['feature_version'])}</td><th>Training dataset</th><td>{_e(meta['training_dataset_version'])}</td></tr>
<tr><th>Trained at</th><td>{_e(meta['trained_at'])}</td><th>Deployed at</th><td>{_e(reg_entry.get('deployment_timestamp') if reg_entry else '—')}</td></tr>
<tr><th>Rows used</th><td>{meta['dataset_rows_used']}</td><th>Split (train/valid/test)</th><td>{m['split_sizes']['train']} / {m['split_sizes']['valid']} / {m['split_sizes']['test']}</td></tr>
<tr><th>Boosting rounds</th><td>{m['best_iteration']}</td><th>Status</th><td>{_e(status)}</td></tr>
</table>

<h2>Performance on held-out test set</h2>
<table>
<tr><th>Model</th><th>ROC-AUC ↑</th><th>PR-AUC ↑</th><th>Brier ↓</th><th>Log-loss ↓</th></tr>
<tr><td><b>LightGBM + isotonic calibration (deployed)</b></td><td>{cmp('roc_auc', True)}</td><td>{cmp('pr_auc', True)}</td><td>{cmp('brier', False)}</td><td>{cmp('log_loss', False)}</td></tr>
<tr><td>LightGBM uncalibrated</td><td>{m['lightgbm_uncalibrated']['roc_auc']:.4f}</td><td>{m['lightgbm_uncalibrated']['pr_auc']:.4f}</td><td>{m['lightgbm_uncalibrated']['brier']:.4f}</td><td>{m['lightgbm_uncalibrated']['log_loss']:.4f}</td></tr>
<tr><td>Logistic regression baseline</td><td>{base['roc_auc']:.4f}</td><td>{base['pr_auc']:.4f}</td><td>{base['brier']:.4f}</td><td>{base['log_loss']:.4f}</td></tr>
</table>

<h2>Risk bands (test set)</h2>
<table>
<tr><th>Band</th><th>Probability range</th><th>Students</th><th>Share of students</th><th>Observed disengagement</th><th>Share of all disengaged captured</th></tr>
{''.join(f"<tr><td>{_pill(b)}</td><td>{r}</td><td>{bands[b]['students']}</td><td>{_pct(bands[b]['share_of_students'])}</td><td>{_pct(bands[b]['observed_disengagement_rate'])}</td><td>{_pct(bands[b]['share_of_all_disengaged_captured'])}</td></tr>"
          for b, r in (("HIGH", f"≥ {m['risk_band_thresholds']['HIGH']:.0%}"),
                       ("MEDIUM", f"{m['risk_band_thresholds']['MEDIUM']:.0%} – {m['risk_band_thresholds']['HIGH']:.0%}"),
                       ("LOW", f"< {m['risk_band_thresholds']['MEDIUM']:.0%}")))}
</table>

<h2>Explainability &amp; calibration</h2>
<div class="imgs">
 <img src="{_img_b64(mdir / 'feature_importance.png')}" alt="Feature importance">
 <img src="{_img_b64(mdir / 'calibration.png')}" alt="Calibration">
</div>
<table style="margin-top:14px">
<tr><th>Feature</th><th>Mean |SHAP|</th><th>Monotone constraint</th></tr>
{''.join(f"<tr><td>{_e(config.FEATURE_LABELS[k])}</td><td>{v:.4f}</td><td>{'higher → more risk' if meta['monotone_constraints'][k] > 0 else 'higher → less risk'}</td></tr>" for k, v in imp.items())}
</table>

<h2>Provisional decisions awaiting approval (PRD §36–37)</h2>
<ul>
<li>Risk-band thresholds MEDIUM ≥ {m['risk_band_thresholds']['MEDIUM']}, HIGH ≥ {m['risk_band_thresholds']['HIGH']}</li>
<li>Evidence gate: {_e(config.EVIDENCE_RULES)}</li>
<li>Q6: "Prediction Unavailable" returned as INSUFFICIENT_EVIDENCE with no prediction record</li>
<li>Q7: prediction_score = prediction_confidence = 100·max(p, 1−p); risk_probability = calibrated p</li>
<li>Feature formulas fe-v1, pass mark {config.PASS_MARK_PERCENT}% fallback, probabilities clamped to {config.PROBABILITY_BOUNDS}</li>
<li>Not yet done: fairness / subgroup evaluation (needs real demographic data and an approved policy)</li>
</ul>
"""
    out_dir = Path(out_dir or REPORTS_DIR)
    out_dir.mkdir(parents=True, exist_ok=True)
    html_path = out_dir / f"model_report_{model_version}.html"
    html_path.write_text(_page(f"Model Evaluation Report — {model_version}", body))

    md = [f"# Model Evaluation Report — {model_version}", "",
          f"Status: **{status}** · Feature version `{meta['feature_version']}` · Dataset `{meta['training_dataset_version']}`", ""]
    if synthetic:
        md += ["> ⚠️ Trained on SIMULATED data — not for real-student decisions.", ""]
    md += ["## Key findings", *[f"- {f}" for f in findings], "",
           "## Test metrics", "| Model | ROC-AUC | PR-AUC | Brier | Log-loss |", "|---|---|---|---|---|",
           f"| LightGBM (calibrated) | {gbm['roc_auc']} | {gbm['pr_auc']} | {gbm['brier']} | {gbm['log_loss']} |",
           f"| Logistic baseline | {base['roc_auc']} | {base['pr_auc']} | {base['brier']} | {base['log_loss']} |", "",
           "## Risk bands", "| Band | Students | Share | Observed disengagement | Captured |", "|---|---|---|---|---|",
           *[f"| {b} | {bands[b]['students']} | {_pct(bands[b]['share_of_students'])} | {_pct(bands[b]['observed_disengagement_rate'])} | {_pct(bands[b]['share_of_all_disengaged_captured'])} |" for b in ("HIGH", "MEDIUM", "LOW")]]
    md_path = out_dir / f"model_report_{model_version}.md"
    md_path.write_text("\n".join(md) + "\n")
    return {"html": html_path, "markdown": md_path}


