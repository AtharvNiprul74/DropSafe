def _e(x) -> str:
    return html.escape("" if x is None else str(x))


def _pill(label: str) -> str:
    return f'<span class="pill" style="background:{BAND_COLORS.get(label, "#777")}">{_e(label)}</span>'


def _img_b64(path: Path) -> str:
    return "data:image/png;base64," + base64.b64encode(path.read_bytes()).decode()


def _fig_b64(fig) -> str:
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=130, bbox_inches="tight")
    plt.close(fig)
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()


def _page(title: str, body: str) -> str:
    return (f"<!doctype html><html lang='en'><head><meta charset='utf-8'>"
            f"<meta name='viewport' content='width=device-width,initial-scale=1'>"
            f"<title>{_e(title)}</title><style>{CSS}</style></head>"
            f"<body><div class='wrap'>{body}<footer>Generated by DropSafe ML Service · "
            f"{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}</footer></div></body></html>")


def _pct(x) -> str:
    return "—" if x is None else f"{100 * x:.1f}%"


