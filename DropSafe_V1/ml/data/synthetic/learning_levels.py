def generate_uuid():
    timestamp_ms = int(datetime.now(timezone.utc).timestamp() * 1000)
    random_bits = uuid.uuid4().int
    value = (
        ((timestamp_ms & ((1 << 48) - 1)) << 80)
        | (0x7 << 76)
        | (((random_bits >> 64) & 0xFFF) << 64)
        | (0b10 << 62)
        | (random_bits & ((1 << 62) - 1))
    )
    return str(uuid.UUID(int=value))


def utc_now():
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def load_programs():
    if not PROGRAMS_FILE.exists():
        raise FileNotFoundError(
            f"Missing {PROGRAMS_FILE}. Generate learning_programs.csv first."
        )
    df = pd.read_csv(PROGRAMS_FILE, dtype={"id": str, "organization_id": str})
    required = ["id", "organization_id", "program_code", "name"]
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(f"learning_programs.csv is missing columns: {missing}")
    if df.empty:
        raise ValueError("learning_programs.csv is empty.")
    if df["id"].duplicated().any():
        raise ValueError("learning_programs.csv contains duplicate IDs.")
    return df


def generate_learning_levels(programs):
    """Create exactly one level 1-4 for each program."""
    rows = []
    for program in programs.to_dict("records"):
        for level_number, level_name in enumerate(LEVEL_NAMES, start=1):
            now = utc_now()
            rows.append({
                "id": generate_uuid(),
                "organization_id": program["organization_id"],
                "learning_program_id": program["id"],
                "level_number": level_number,
                "name": f"{level_name} - {program['program_code']}",
                "description": f"Synthetic {level_name.lower()} for {program['name']}",
                "status": "ACTIVE",
                "created_at": now,
                "updated_at": now,
                "created_by": None,
                "updated_by": None,
            })
    return pd.DataFrame(rows)


def validate(df, programs):
    required = [
        "id", "organization_id", "learning_program_id", "level_number",
        "name", "description", "status", "created_at", "updated_at",
        "created_by", "updated_by"
    ]
    missing_columns = [c for c in required if c not in df.columns]
    valid_programs = set(programs["id"].astype(str))
    program_org = dict(zip(programs["id"].astype(str), programs["organization_id"].astype(str)))
    mapped_org = df["learning_program_id"].astype(str).map(program_org)
    results = {
        "rows": len(df),
        "missing_columns": missing_columns,
        "duplicate_ids": int(df["id"].duplicated().sum()),
        "duplicate_program_level": int(df.duplicated(["organization_id", "learning_program_id", "level_number"]).sum()),
        "invalid_level_numbers": int((~df["level_number"].between(1, 4)).sum()),
        "invalid_statuses": int((~df["status"].isin(STATUSES)).sum()),
        "invalid_program_refs": int((~df["learning_program_id"].astype(str).isin(valid_programs)).sum()),
        "organization_mismatches": int((mapped_org != df["organization_id"].astype(str)).sum()),
        "validation_passed": (
            not missing_columns
            and not df["id"].duplicated().any()
            and not df.duplicated(["organization_id", "learning_program_id", "level_number"]).any()
            and df["level_number"].between(1, 4).all()
            and df["status"].isin(STATUSES).all()
            and df["learning_program_id"].astype(str).isin(valid_programs).all()
            and (mapped_org == df["organization_id"].astype(str)).all()
        )
    }
    return results


def main():
    programs = load_programs()
    df = generate_learning_levels(programs)
    RAW_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    df.to_csv(OUTPUT_FILE, index=False)
    result = validate(df, programs)
    REPORT_FILE.write_text(
        "# Learning Levels Synthetic Dataset\n\n"
        f"- Programs: {len(programs)}\n"
        f"- Levels generated: {len(df)}\n"
        "- Rule: exactly four unique levels (1-4) per program\n"
        "- Target/dropout labels: not generated\n\n"
        f"## Validation\n\n```text\n{result}\n```\n",
        encoding="utf-8"
    )
    print(f"Programs: {len(programs)}")
    print(f"Learning levels: {len(df)}")
    print(f"CSV: {OUTPUT_FILE}")
    print(f"Report: {REPORT_FILE}")
    print(f"Validation: {'PASS' if result['validation_passed'] else 'FAIL'}")
    if not result["validation_passed"]:
        raise SystemExit("Learning-level validation failed.")


if __name__ == "__main__":
    main()
