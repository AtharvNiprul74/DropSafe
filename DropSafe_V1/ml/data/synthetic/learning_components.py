def load_academic_periods():
    """
    Load the academic periods generated by the previous step.
    """

    if not PERIODS_FILE.exists():

        raise FileNotFoundError(
            "academic_periods.csv was not found.\n"
            "Run academic_periods.py first:\n\n"
            "python data\\synthetic\\academic_periods.py"
        )

    df = pd.read_csv(PERIODS_FILE)

    required_columns = [
        "id",
        "organization_id",
    ]

    missing_columns = [
        column
        for column in required_columns
        if column not in df.columns
    ]

    if missing_columns:

        raise ValueError(
            "academic_periods.csv is missing required "
            f"columns: {missing_columns}"
        )

    if df.empty:

        raise ValueError(
            "academic_periods.csv contains no records."
        )

    return df


# ============================================================
# Synthetic dataset generation
# ============================================================

def generate_learning_components(academic_periods):
    """
    Generate synthetic learning component records.

    Every academic period receives COMPONENTS_PER_PERIOD
    components. This guarantees that every enrollment can
    reference a learning component in the same organization
    and academic period as its enrollment.
    """

    rows = []

    component_number = 0

    for _, period in academic_periods.iterrows():

        for _ in range(COMPONENTS_PER_PERIOD):

            component_number += 1

            maximum_marks = random.choice(
                [50, 75, 100]
            )

            passing_percentage = random.choice(
                [35, 40, 50]
            )

            passing_marks = int(
                maximum_marks
                * passing_percentage
                / 100
            )

            now = utc_now()

            row = {
                "id": generate_uuid(),
                "organization_id": period["organization_id"],
                "academic_period_id": period["id"],
                "component_code": (
                    f"CMP-{component_number:05d}"
                ),
                "name": (
                    f"Learning Component "
                    f"{component_number}"
                ),
                "description": (
                    f"Synthetic learning component "
                    f"{component_number}"
                ),
                "component_type": random.choice(
                    COMPONENT_TYPES
                ),
                "maximum_marks": maximum_marks,
                "passing_marks": passing_marks,
                "status": random.choice(
                    STATUSES
                ),
                "created_at": now,
                "updated_at": now,
                "created_by": None,
                "updated_by": None,
            }

            rows.append(row)

    return pd.DataFrame(rows)


